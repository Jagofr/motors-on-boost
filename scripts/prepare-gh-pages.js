#!/usr/bin/env node
/**
 * Builds the static GitHub Pages distribution folder from `web/`.
 * Used both locally (.vscode/build-deploy.ps1 & Playwright) and in GitHub Actions.
 *
 * Usage:
 *   node scripts/prepare-gh-pages.js [outputDir]
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const WEB_DIR = path.join(ROOT, 'web');
const OUT_DIR = path.resolve(ROOT, process.argv[2] || path.join('dist', 'gh-pages'));

// IIS-specific server files must never be shipped to static GitHub Pages.
const EXCLUDED_FILES = new Set(['web.config', 'relay.ashx', 'game.hl']);

function copyDirClean(src, dst, relPrefix = '') {
  fs.mkdirSync(dst, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const rel = relPrefix ? `${relPrefix}/${entry.name}` : entry.name;
    if (EXCLUDED_FILES.has(rel) || EXCLUDED_FILES.has(entry.name)) continue;
    const srcPath = path.join(src, entry.name);
    const dstPath = path.join(dst, entry.name);
    if (entry.isDirectory()) {
      copyDirClean(srcPath, dstPath, rel);
    } else if (entry.isFile()) {
      fs.copyFileSync(srcPath, dstPath);
    }
  }
}

if (!fs.existsSync(WEB_DIR)) {
  throw new Error(`Missing web source directory: ${WEB_DIR}`);
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
copyDirClean(WEB_DIR, OUT_DIR);

// Disable Jekyll processing so static assets load cleanly under any filename.
fs.writeFileSync(path.join(OUT_DIR, '.nojekyll'), '');

// Configure GitHub Pages runtime environment:
// - Service Worker COOP/COEP header injection enabled
// - Live *.github.io connects cross-origin to primary IIS relay (CORS enabled on relay.ashx)
// - Local 127.0.0.1/localhost simulation stays pure static BroadcastChannel (no external calls)
const relayMode = process.env.MOB_GH_RELAY_MODE || 'remote';
const relayOrigin = process.env.MOB_GH_RELAY_ORIGIN || 'https://mob.24-7.ro';
const ghEnv = {
  target: 'gh-pages',
  enableCoiServiceWorker: true,
  relayMode,
  relayOrigin,
  staticOfflineHosts: ['127.0.0.1', 'localhost']
};
fs.writeFileSync(
  path.join(OUT_DIR, 'mob-env.js'),
  `/* Auto-generated by scripts/prepare-gh-pages.js for GitHub Pages static mirror. */\nwindow.__MOB_ENV__ = ${JSON.stringify(ghEnv, null, 2)};\n`
);

// Enable COOP/COEP/CORP response header injection in the packaged Service Worker.
const swOutPath = path.join(OUT_DIR, 'sw.js');
const swSrc = fs.readFileSync(swOutPath, 'utf8');
if (!swSrc.includes('const FORCE_COI_HEADERS = false;')) {
  throw new Error('Expected `const FORCE_COI_HEADERS = false;` anchor in web/sw.js');
}
fs.writeFileSync(
  swOutPath,
  swSrc.replace('const FORCE_COI_HEADERS = false;', 'const FORCE_COI_HEADERS = true;')
);

const required = [
  '.nojekyll',
  'index.html',
  'mob-env.js',
  'sw.js',
  'ui-overlay.js',
  'ui-overlay.css',
  'manifest.json',
  'game.wasm',
  'xgpu.wasm',
  'xwindow.wasm',
  'ash_browser.js',
  'ash_browser_bg.wasm'
];
for (const reqFile of required) {
  if (!fs.existsSync(path.join(OUT_DIR, reqFile))) {
    throw new Error(`Missing required gh-pages artifact: ${reqFile}`);
  }
}

console.log(`[GH-PAGES OK] Packaged static WebGPU build -> ${OUT_DIR}`);
